// Quote document: a printable quotation with line items and totals, export, and the connectors
// that can carry it onward (through the agent, which always asks before acting).
import { api, h, icon, fmt, chip } from '../ui.js';
import { opt, money, backLink, logoTile } from './ops-kit.js';
import { quoteNo } from './quotes.js';

const ONWARD = ['slack', 'salesforce', 'hubspot', 'googledrive', 'dropbox', 'docusign'];

export async function renderQuote(id, ctx) {
  const q = await api(`/quotes/${id}`);
  const [dr, cx] = await Promise.all([
    q.design_request_id ? api(`/design-requests/${q.design_request_id}`).catch(() => null) : null,
    api('/connectors').catch(() => ({ items: [] })),
  ]);
  const cur = q.currency || 'USD';
  const lines = Array.isArray(q.lines) ? q.lines : [];
  const ws = ctx.session?.workspace;
  const rate = q.subtotal_minor ? Math.round((Number(q.tax_minor || 0) / (Number(q.subtotal_minor) - Number(q.discount_minor || 0))) * 1000) / 10 : 0;
  const taxLabel = q.tax_label || (rate ? `VAT ${rate}%` : 'Tax 0% (reverse charge or zero-rated export)');
  ctx.setCrumbs('Quotes', quoteNo(q));

  const doc = h('article.quote-doc.card',
    h('header.qd-head',
      h('div', h('div.qd-brand', h('span.qd-mark', (ws?.name || 'P')[0]), ws?.name || 'Supplier'),
        h('div.xs.muted', [ws?.profile?.hq?.city, ws?.profile?.hq?.country].filter(Boolean).join(', ') || '')),
      h('div.qd-meta', h('div.h3', 'Quotation'), h('div.mono.muted', quoteNo(q)))),
    h('div.qd-parties',
      party('Prepared for', opt(dr?.customer), dr?.subject),
      party('Issued', fmt.date(q.created_at || q.issued_at), null),
      party('Valid until', q.valid_until ? fmt.date(q.valid_until) : '—', null),
      party('Currency', cur, null)),
    h('table.table.qd-lines',
      h('thead', h('tr', h('th', 'Item'), h('th.r', 'Qty'), h('th.r', 'Unit price'), h('th.r', 'Amount'))),
      h('tbody', lines.length ? lines.map((l) => h('tr',
        h('td', h('div', opt(l.description)), h('div.mono.muted', opt(l.sku, ''))),
        h('td.r.num', opt(l.qty)),
        h('td.r.num', money(l.unit_price_minor, cur)),
        h('td.r.num', money(l.line_total_minor ?? (l.qty || 0) * (l.unit_price_minor || 0), cur)))) : h('tr', h('td', { colspan: '4' }, h('div.empty', 'No line items'))))),
    h('div.qd-totals',
      row('Subtotal', money(q.subtotal_minor, cur)),
      Number(q.discount_minor) ? row('Discount', `− ${money(q.discount_minor, cur)}`) : null,
      row(taxLabel, money(q.tax_minor, cur)),
      h('div.qd-total', h('span', 'Total'), h('span.num', money(q.total_minor, cur)))),
    h('footer.qd-foot', h('div.xs.muted', q.terms || 'Prices exclude installation unless listed. Delivery and payment terms as agreed on order. Generated by Pactovio from the matched datasheets; review before sending.')));

  const items = cx.items || [];
  const onward = ONWARD.map((p) => items.find((c) => c.provider === p)).filter(Boolean);
  const prompt = (p) => `Share quote ${quoteNo(q)} (${q.id}) for ${opt(dr?.customer, 'the customer')} via ${p.name}.`;
  const side = h('aside.qd-side',
    h('div.card.qd-panel',
      h('div.small', { style: { fontWeight: 510 } }, 'Status'), h('div', { style: { margin: '6px 0 14px' } }, chip(q.status || 'draft')),
      h('a.btn.btn-primary', { href: `/api/quotes/${q.id}/export`, download: '', style: { width: '100%' } }, icon('download'), 'Export .docx'),
      dr ? h('a.btn.btn-secondary', { href: `#/quotes/${dr.id}`, style: { width: '100%', marginTop: '8px' } }, 'View design request') : null),
    h('div.card.qd-panel',
      h('div.small', { style: { fontWeight: 510 } }, 'Send onward'),
      h('div.xs.muted', { style: { margin: '2px 0 10px' } }, 'The agent prepares it and asks you to confirm. Nothing is sent without your click.'),
      onward.length ? onward.map((c) => h('button.onward-row', {
        disabled: c.status !== 'connected',
        onclick: () => { sessionStorage.setItem('pv_prefill', prompt(c)); location.hash = '#/agent'; },
      }, logoTile(c.provider, 24, c.name), h('div.onward-text', h('div.small', c.name), h('div.xs.muted', c.status === 'connected' ? opt(c.account_label, 'Connected') : 'Not connected')), icon('chev'))) : h('div.xs.muted', 'No connectors available.')));

  return h('div', backLink('#/quotes', 'All quotes'),
    h('div.qd-layout', doc, side));
}

function party(k, v, sub) { return h('div', h('div.xs.muted', k), h('div.small', { style: { fontWeight: 510 } }, v), sub ? h('div.xs.muted.clamp', sub) : null); }
function row(k, v) { return h('div.qd-row', h('span.muted', k), h('span.num', v)); }
