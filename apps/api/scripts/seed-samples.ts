import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { buildHarbour, buildKestrel, EMAILS, rfpPdf, r2KeyFor, type SampleFile } from '@pactovio/quote/samples';
import { catalogSql, evidenceSql, KESTREL_WS } from './seed-samples-sql';
import { designSql } from './seed-samples-design';

/**
 * Generates the Sample-company evidence (Harbour Digital) and catalogue (Kestrel Sensing): PDFs into fixtures/samples/,
 * SQL into .wrangler/seed-samples.sql, then optionally applies D1 + R2.
 *   tsx scripts/seed-samples.ts                       generate files + SQL only
 *   tsx scripts/seed-samples.ts --apply --local [--persist-to .wrangler/state-C-design]
 *   tsx scripts/seed-samples.ts --apply --remote
 */
const api = process.cwd();
const fixtures = resolve(api, '../../fixtures/samples');
const args = process.argv.slice(2);
const flag = (n: string) => args.includes(n);
const val = (n: string) => args[args.indexOf(n) + 1];

function write(rel: string, bytes: Uint8Array | string): void {
  const p = join(fixtures, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, bytes);
}

async function main(): Promise<void> {
  const scanPath = join(fixtures, 'harbour-digital/iso-9001-certificate-scan.png');
  const scan = existsSync(scanPath) ? new Uint8Array(readFileSync(scanPath)) : null;
  const harbour = await buildHarbour(scan);
  const kestrel = await buildKestrel();
  const files: SampleFile[] = [...harbour, ...kestrel];
  for (const f of harbour) write(`harbour-digital/${f.filename}`, f.bytes);
  for (const f of kestrel) write(`kestrel-sensing/${f.filename}`, f.bytes);
  write('emails/attachments/RFP-CCC-2026-14-planning-enforcement.pdf', (await rfpPdf()).bytes);
  for (const e of EMAILS) write(`emails/${e.id}.json`, `${JSON.stringify(e, null, 2)}\n`);

  const sql = [...evidenceSql(files), ...catalogSql(kestrel), ...designSql()].join('\n');
  const sqlPath = join(api, '.wrangler/seed-samples.sql');
  mkdirSync(dirname(sqlPath), { recursive: true });
  writeFileSync(sqlPath, `-- generated by scripts/seed-samples.ts (Sample companies, fictional)\n${sql}\n`);
  process.stderr.write(`wrote ${files.length} files to ${fixtures} and ${sqlPath}\n`);
  if (!flag('--apply')) return;

  const target = flag('--remote') ? ['--remote'] : ['--local', ...(val('--persist-to') ? ['--persist-to', val('--persist-to')!] : [])];
  const cf = (a: string[]) => execFileSync('bash', ['./cf.sh', ...a], { cwd: api, stdio: ['ignore', 'ignore', 'inherit'] });
  cf(['d1', 'execute', 'pactovio', ...target, `--file=${sqlPath}`]);
  for (const f of files) {
    const dir = f.workspace_id === KESTREL_WS ? 'kestrel-sensing' : 'harbour-digital';
    cf(['r2', 'object', 'put', `pactovio-files/${r2KeyFor(f.workspace_id, f.filename)}`, `--file=${join(fixtures, dir, f.filename)}`, `--content-type=${f.mime}`, ...target]);
  }
  process.stderr.write(`applied D1 + ${files.length} R2 objects (${target.join(' ')})\n`);
}

main().catch((e) => { process.stderr.write(`${e instanceof Error ? e.message : e}\n`); process.exit(1); });
