import { toRow } from '@pactovio/contracts';

/** Primary keys per table, for idempotent upserts. */
const PK: Record<string, string[]> = {
  workspaces: ['id'], tenders: ['id'], tender_matches: ['workspace_id', 'tender_id'], intakes: ['id'], documents: ['id'],
  runs: ['id'], run_steps: ['id'], requirements: ['id'], verdicts: ['id'], evidence: ['id'], answers: ['id'],
  buyer_intel: ['buyer_key'], products: ['id'], price_rules: ['id'], design_requests: ['id'], quotes: ['id'],
  connectors: ['id'], subscriptions: ['workspace_id'], credit_ledger: ['id'],
};

const q = (v: string | number | null): string =>
  v === null ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`;

export class Sql {
  readonly stmts: string[] = [];
  /** Insert-or-update one row. Objects/arrays become *_json columns, booleans 0/1 (see contracts/rows). */
  put(table: string, obj: Record<string, unknown>): void {
    const row = toRow(obj);
    const cols = Object.keys(row);
    const pk = PK[table];
    if (!pk) throw new Error(`no pk for ${table}`);
    const upd = cols.filter((c) => !pk.includes(c)).map((c) => `${c} = excluded.${c}`).join(', ');
    this.stmts.push(
      `INSERT INTO ${table} (${cols.join(', ')}) VALUES (${cols.map((c) => q(row[c]!)).join(', ')}) ON CONFLICT(${pk.join(', ')}) DO ${upd ? `UPDATE SET ${upd}` : 'NOTHING'};`,
    );
  }
  toString(): string {
    return `-- generated by scripts/seed.ts; idempotent upserts of sample data\n${this.stmts.join('\n')}\n`;
  }
}

