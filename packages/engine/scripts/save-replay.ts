/**
 * Save a finished live run as the bundled replay for a tender.
 * Usage: tsx scripts/save-replay.ts <runId> <tenderId> [baseUrl=http://localhost:8792] [workspaceId=ws_harbour_digital]
 * Reads the run, matrix, verdicts and drafts through the public API of a local dev server and writes
 * packages/engine/replay/<tenderId>.json (+ regenerates replay/index.ts).
 */
import { readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { toRow } from '@pactovio/contracts';
import type { ReplaySnapshot } from '../src/replay';

const [runId, tenderId, base = 'http://localhost:8792', workspaceId = 'ws_harbour_digital'] = process.argv.slice(2);
if (!runId || !tenderId) throw new Error('usage: save-replay <runId> <tenderId> [baseUrl] [workspaceId]');
const get = async <T>(path: string): Promise<T> => {
  const r = await fetch(`${base}/api${path}`);
  if (!r.ok) throw new Error(`${path}: ${r.status}`);
  return (await r.json()) as T;
};
type Obj = Record<string, unknown>;
const run = await get<{ run: Obj; steps: Obj[] }>(`/runs/${runId}`);
if (run.run.status !== 'completed' || run.run.workspace_id !== workspaceId) throw new Error(`run ${runId} is ${run.run.status} in ${run.run.workspace_id}`);
const matrix = await get<{ requirements: Obj[]; verdicts: Obj[] }>(`/tenders/${tenderId}/matrix`);
const answers = await get<{ items: Obj[] }>(`/tenders/${tenderId}/answers`);
const snap: ReplaySnapshot = {
  tender_id: tenderId, workspace_id: workspaceId, recorded_at: String(run.run.started_at), source_run_id: runId,
  steps: run.steps.filter((s) => s.status === 'ok').map((s) => ({ purpose: String(s.purpose), model: (s.model as string | null) ?? null, status: 'ok' as const, tokens_in: Number(s.tokens_in), tokens_out: Number(s.tokens_out), tokens_cached: Number(s.tokens_cached), ms: Number(s.ms), cost_usd: Number(s.cost_usd), summary: (s.summary as string | null) ?? null })),
  requirements: matrix.requirements.map((r) => toRow(r)),
  verdicts: matrix.verdicts.map((r) => toRow(r)),
  answers: answers.items.filter((a) => a.status === 'draft' && !String(a.id).startsWith('ans_sample')).map((r) => toRow(r)),
};
const dir = resolve(process.cwd(), 'replay');
writeFileSync(join(dir, `${tenderId}.json`), JSON.stringify(snap));
const files = readdirSync(dir).filter((f) => f.endsWith('.json'));
const ident = (f: string) => `r_${f.replace(/\.json$/, '').replace(/\W/g, '_')}`;
writeFileSync(join(dir, 'index.ts'), `import type { ReplaySnapshot } from '../src/replay';\n${files.map((f) => `import ${ident(f)} from './${f}';`).join('\n')}\n\n/** Recorded live runs bundled with the Worker, keyed by tender id. Regenerated by \`scripts/save-replay.ts\`. */\nexport const REPLAYS: Record<string, ReplaySnapshot> = {\n${files.map((f) => `  '${f.replace(/\.json$/, '')}': ${ident(f)} as unknown as ReplaySnapshot,`).join('\n')}\n};\n`);
process.stderr.write(`saved ${snap.steps.length} steps, ${snap.requirements.length} requirements, ${snap.verdicts.length} verdicts, ${snap.answers.length} drafts\n`);
